"""Role orchestration for ground-connected causal JIT frontier acquisition.

This module intentionally leaves the historical RSI-anchor frontier runner
untouched for reproducibility. Prospective causal plans are executed here:
proposal anchors identify locked centerline x slices only, while every physical
candidate starts at the authoritative natural ground reset and is generated by
real env.step dynamics before continuation RSI labeling.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import jax

from .acquisition.causal_jump import (
    ACQUISITION_MODE,
    collect_ground_connected_jump_candidates,
)
from .checkpoint import load_checkpoint
from .config import file_sha256
from .iterative_frontier_protocol import (
    ROLE_SCHEMA,
    ROLES,
    _acquisition_phase_support,
    _completed_acquisition,
    _completed_labeling,
    _load_plan,
    _logical_rows,
    _phase_counts,
    _read,
    _selected_policy,
    _source_tube,
    _verify_self_hash,
    _write,
    canonical_sha256,
)
from .ppo import make_checkpoint_policy
