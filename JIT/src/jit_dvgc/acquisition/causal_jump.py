"""Fixed-jump-start causal frontier acquisition for trajectory-centered JIT.

A continuation-successful RSI state is not, by itself, jumping-capability
evidence. This module therefore generates every prospective Jump-Tube candidate
from the authoritative fixed ground jump-start reset and advances only through env.step.
RSI is reserved for the later continuation evaluation of a state that has
already been reached causally.

The nominal centerline supplies longitudinal target slices only. Source-Tube
states are never used as physical reset points in this acquisition mode. For a
target x slice, the frozen unified policy is rolled forward from the jump start and
a bounded action perturbation is activated within a predeclared causal lookback
window. The first physically valid state in the target 0.1 m slice is captured.

For downstream candidates the state must be post-Apex, descending, and still
pre-contact. Post-landing recovery cannot become Jump-Tube frontier evidence.
"""
